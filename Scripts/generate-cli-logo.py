#!/usr/bin/env python3
"""Convert the checked-in brand image to compact terminal pixel data. Requires Pillow."""
import hashlib
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "MacMenuBar/Resources/HashFleetStatusIcon.png"
OUTPUT = ROOT / "Sources/hashfleet/DashboardLogo.swift"
ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz+/"

# Reuse the menu bar's transparent miner, keeping the casing, display, fan, and feet.
# One terminal cell contains two vertically stacked square pixels (the ▀ glyph).
image = Image.open(SOURCE).convert("RGBA")
quantized = image.convert("RGB").quantize(colors=64, method=Image.Quantize.MEDIANCUT)
palette = quantized.getpalette()[:192]
colors = [(palette[i] << 16) | (palette[i + 1] << 8) | palette[i + 2] for i in range(0, 192, 3)]
lines = [
    "// Generated by Scripts/generate-cli-logo.py from the transparent Hash Fleet menu bar artwork.",
    f"// Source SHA-256: {hashlib.sha256(SOURCE.read_bytes()).hexdigest()}",
    "// Each character indexes one sRGB pixel; '.' means terminal background (-1).",
    "enum DashboardLogo {",
    f'    static let alphabet = Array("{ALPHABET}")',
    "    static let colors: [UInt32] = [",
]
for index in range(0, len(colors), 8):
    lines.append("        " + ", ".join(f"0x{color:06X}" for color in colors[index:index + 8]) + ",")
lines.append("    ]")
for name, width, height in [("small", 20, 24), ("medium", 24, 30), ("large", 32, 40)]:
    scaled = ImageOps.contain(image, (width, height), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (width, height))
    canvas.paste(scaled, ((width - scaled.width) // 2, (height - scaled.height) // 2))
    pixels = canvas.convert("RGB").quantize(palette=quantized, dither=Image.Dither.NONE)
    alpha = canvas.getchannel("A")
    lines.append(f"    static let {name}: [[Int]] = decode([")
    for row in range(height):
        # Terminals cannot blend a pixel with an unknown theme background. Preserve
        # the silhouette with a binary alpha mask instead of painting a black matte.
        encoded = "".join(
            ALPHABET[pixels.getpixel((column, row))] if alpha.getpixel((column, row)) >= 128 else "."
            for column in range(width)
        )
        lines.append(f'        "{encoded}",')
    lines.append("    ])")
lines += [
    "    private static func decode(_ rows: [String]) -> [[Int]] {",
    "        let indices = Dictionary(uniqueKeysWithValues: alphabet.enumerated().map { ($0.element, $0.offset) })",
    "        return rows.map { $0.map { $0 == \".\" ? -1 : indices[$0]! } }",
    "    }",
    "}",
]
OUTPUT.write_text("\n".join(lines) + "\n")
print(f"Generated {OUTPUT.relative_to(ROOT)} from {SOURCE.relative_to(ROOT)}")
